// Bundles prisma/migrations/*/migration.sql into a TypeScript module so the
// browser (and the tests) can apply them to PGlite. Run by `npm run db:bundle`,
// and automatically before dev/build/test.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'prisma', 'migrations');
const names = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'migration.sql')))
  .map((d) => d.name)
  .sort();

const migrations = names.map((name) => {
  const sql = readFileSync(join(dir, name, 'migration.sql'), 'utf8');
  return { name, checksum: createHash('sha256').update(sql).digest('hex'), sql };
});

const out = `// GENERATED by scripts/build-migrations.mjs from prisma/migrations — do not edit.
export interface Migration {
  name: string;
  /** SHA-256 of the migration file, as recorded by Prisma Migrate. */
  checksum: string;
  sql: string;
}

export const MIGRATIONS: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;
const dest = join(root, 'src', 'db', 'migrations.generated.ts');
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, out);
console.log(`bundled ${migrations.length} migration(s) -> src/db/migrations.generated.ts`);

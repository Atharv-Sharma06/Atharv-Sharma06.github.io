// Bundles the collector CLI (src/import/claude-code/collector-cli.ts) into one
// dependency-free file that people download from the site and run with Node:
//   public/tools/claude-lifetime-collect.mjs
// It shares its extraction code with the in-browser importer, so rebuild it whenever
// src/import/claude-code/ or src/import/util/lines.ts changes.
//   node scripts/build-collector.mjs [--outfile <file>]
import { mkdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outArg = process.argv.indexOf('--outfile');
const outfile = outArg === -1 ? join(root, 'public', 'tools', 'claude-lifetime-collect.mjs') : resolve(process.argv[outArg + 1]);

const banner = `#!/usr/bin/env node
/* eslint-disable */
// Claude Lifetime collector.
//
// Reads Claude Code's session transcripts on this computer and keeps a small ledger of
// their token usage, for import into Claude Lifetime. It reads below your Claude Code
// config directory, writes only the ledger file, and uses no network and no packages.
// The ledger never contains message text.
//
//   node claude-lifetime-collect.mjs --help
//
// GENERATED by scripts/build-collector.mjs from src/import/claude-code/collector-cli.ts.
// Do not edit; change the sources and rebuild.`;

mkdirSync(dirname(outfile), { recursive: true });
await build({
  entryPoints: [join(root, 'src', 'import', 'claude-code', 'collector-cli.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  // fs.openAsBlob needs Node 19.8; 20 is the oldest release line that has it and is still maintained.
  target: 'node20',
  // Resolves the '@/...' imports the same way the app does.
  tsconfig: join(root, 'tsconfig.json'),
  banner: { js: banner },
  // Left readable on purpose: people should be able to check what the tool does before running it.
  minify: false,
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
});
console.log(`bundled collector -> ${relative(root, outfile) || outfile} (${statSync(outfile).size} bytes)`);
